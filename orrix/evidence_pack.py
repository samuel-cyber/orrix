"""A one-page evidence PDF, built strictly from Facts.

The layout is fixed. Every line on the page comes from a named fact, a
constant string, or a hash of the two. There is no parameter here that a
buyer, a model, a ledger free-text field or a carrier response could reach:
the buyer's message, the Reader's summary, the ledger's item label and every
provider string are not read by this module at all, so none of them can
appear on the page.

The document is deterministic. Its metadata dates come from the facts'
retrieval time rather than the clock, and no identifier is derived from the
current time, so the same facts produce byte-identical output and therefore a
stable hash. The hash printed on the page is the SHA-256 of the canonical
content listed on it, not of the PDF bytes -- a reader can recompute it from
the same facts without a PDF library.

This module holds no write capability and makes no network call.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any

from .audit import canonical_json, sha256_hex
from .facts import (
    CARRIER_DELIVERED_AT,
    CARRIER_STATUS,
    Facts,
    FactStatus,
)

#: Shown in the footer of every page, verbatim. The second sentence is the
#: honest limit of what this document proves.
FOOTER_TEXT = (
    "Generated by Orrix from the facts listed above. "
    "Not verified by a carrier unless stated."
)

TITLE = "Evidence pack"
SUBTITLE = "Facts on record for this dispute"

#: Human labels for the facts the pack prints, in print order. Nothing
#: outside this tuple is read, so a fact added elsewhere does not silently
#: appear in a document a seller may send on.
DISPUTE_ROWS: tuple[tuple[str, str], ...] = (
    ("dispute_id", "Dispute id"),
    ("dispute_amount", "Dispute amount"),
    ("dispute_currency", "Currency"),
    ("reason", "Reason (PayPal)"),
    ("seller_transaction_id", "Transaction id"),
)

TRACKING_ROWS: tuple[tuple[str, str], ...] = (
    ("tracking_carrier", "Carrier"),
    ("tracking_number", "Tracking number"),
    ("delivery_status", "Delivery status"),
    ("delivered_on", "Delivered on"),
)

CARRIER_ROWS: tuple[tuple[str, str], ...] = (
    (CARRIER_STATUS, "Carrier status"),
    (CARRIER_DELIVERED_AT, "Carrier delivered at"),
)

#: How a status reads on the page. "carrier-reported" is never "verified"
#: and never "confirmed".
STATUS_LABELS = {
    FactStatus.CONFIRMED.value: "confirmed by PayPal",
    FactStatus.SELLER_ASSERTED.value: "seller-asserted",
    FactStatus.CARRIER_REPORTED.value: "carrier-reported",
    FactStatus.CONFLICTING.value: "conflicting",
    FactStatus.UNAVAILABLE.value: "unavailable",
}

ORIGIN_LABELS = {
    "paypal_record": "PayPal record",
    "seller_input": "seller input",
    "seller_ledger": "seller ledger",
    "carrier API": "carrier API",
}


class EvidencePackError(ValueError):
    """The pack could not be built. Nothing partial is emitted."""


@dataclass(frozen=True)
class EvidenceRow:
    """One printed line: a label, a value, and where the value came from."""

    label: str
    value: str
    status: str
    origin: str
    recorded_at: str


@dataclass(frozen=True)
class EvidencePack:
    """The content of the document, and its hash, with no PDF involved.

    Separated from rendering so the hash can be computed, compared and
    tested without a PDF library, and so the hash is a statement about the
    facts rather than about fpdf2's output.
    """

    dispute_id: str
    generated_at: str
    dispute_rows: tuple[EvidenceRow, ...]
    tracking_rows: tuple[EvidenceRow, ...]
    carrier_rows: tuple[EvidenceRow, ...]

    @property
    def canonical(self) -> str:
        """The exact bytes the printed hash is taken over."""
        return canonical_json(
            {
                "dispute_id": self.dispute_id,
                "generated_at": self.generated_at,
                "footer": FOOTER_TEXT,
                "sections": [
                    {
                        "name": name,
                        "rows": [
                            {
                                "label": row.label,
                                "value": row.value,
                                "status": row.status,
                                "origin": row.origin,
                                "recorded_at": row.recorded_at,
                            }
                            for row in rows
                        ],
                    }
                    for name, rows in (
                        ("dispute", self.dispute_rows),
                        ("tracking", self.tracking_rows),
                        ("carrier", self.carrier_rows),
                    )
                ],
            }
        )

    @property
    def content_hash(self) -> str:
        return sha256_hex(self.canonical)

    @property
    def all_rows(self) -> tuple[EvidenceRow, ...]:
        return self.dispute_rows + self.tracking_rows + self.carrier_rows


#: Stands in for an absent value. ASCII on purpose: the core PDF fonts are
#: latin-1 only, and a document that cannot render its own placeholder is
#: worse than a plain hyphen.
ABSENT = "-"


def _format_value(value: Any) -> str:
    """A fact value as a printable string. Never a repr, never a blob."""
    if value is None:
        return ABSENT
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, tuple):
        return ", ".join(str(item) for item in value)
    return str(value)


def _row(facts: Facts, name: str, label: str) -> EvidenceRow | None:
    """One row for a named fact, or None when the fact is not present."""
    fact = facts.facts.get(name)
    if fact is None:
        return None

    status = fact.status.value if isinstance(fact.status, FactStatus) else str(fact.status)
    recorded = fact.retrieved_at
    if isinstance(recorded, datetime):
        stamp = recorded.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    else:
        stamp = str(recorded)

    return EvidenceRow(
        label=label,
        value=_format_value(fact.value),
        status=STATUS_LABELS.get(status, status),
        origin=ORIGIN_LABELS.get(fact.source, fact.source),
        recorded_at=stamp,
    )


def build_pack(facts: Facts) -> EvidencePack:
    """Assemble the pack's content from Facts and nothing else."""
    if not isinstance(facts, Facts):
        raise EvidencePackError("an evidence pack is built from Facts")

    def rows(spec: tuple[tuple[str, str], ...]) -> tuple[EvidenceRow, ...]:
        built = (_row(facts, name, label) for name, label in spec)
        return tuple(row for row in built if row is not None)

    # The facts' own retrieval time, not the clock: the same facts must
    # produce the same document and the same hash on every run.
    retrieved = facts.retrieved_at
    if isinstance(retrieved, datetime):
        generated_at = retrieved.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    else:
        generated_at = str(retrieved)

    return EvidencePack(
        dispute_id=facts.dispute_id,
        generated_at=generated_at,
        dispute_rows=rows(DISPUTE_ROWS),
        tracking_rows=rows(TRACKING_ROWS),
        carrier_rows=rows(CARRIER_ROWS),
    )


# -- rendering -----------------------------------------------------------

_MARGIN = 16.0
_LINE = 5.6
_LABEL_WIDTH = 42.0
_VALUE_WIDTH = 64.0
_STATUS_WIDTH = 38.0


def _pdf_timestamp(facts_time: Any) -> datetime:
    """The document's metadata date: the facts' time, never now()."""
    if isinstance(facts_time, datetime):
        stamp = facts_time
    else:
        try:
            stamp = datetime.fromisoformat(str(facts_time).replace("Z", "+00:00"))
        except ValueError:
            # A fixed epoch rather than the clock, so output stays stable.
            stamp = datetime(2000, 1, 1, tzinfo=timezone.utc)
    if stamp.tzinfo is None:
        stamp = stamp.replace(tzinfo=timezone.utc)
    return stamp.astimezone(timezone.utc)


def render_pdf(facts: Facts) -> tuple[bytes, str]:
    """Render the one-page pack. Returns (pdf bytes, content hash).

    Deterministic for the same facts: the creation and modification dates
    are taken from the facts, and fpdf2 is asked not to add a random file
    identifier, so two runs produce identical bytes.
    """
    pack = build_pack(facts)

    try:
        from fpdf import FPDF
    except ImportError as error:  # pragma: no cover - dependency is pinned
        raise EvidencePackError("fpdf2 is not installed") from error

    content_hash = pack.content_hash
    stamp = _pdf_timestamp(facts.retrieved_at)

    pdf = FPDF(orientation="P", unit="mm", format="A4")
    # Uncompressed on purpose. The page is a few hundred bytes of text either
    # way, and leaving the content stream readable means anyone can check the
    # claim this module makes -- that no buyer text, no model output and no
    # free-text field is in here -- with `strings` and a grep, rather than
    # having to trust the tests. It also keeps the bytes stable.
    pdf.set_compression(False)
    # Metadata from the facts, so nothing in the file tracks the clock.
    pdf.set_creation_date(stamp)
    pdf.set_title(f"{TITLE} {pack.dispute_id}")
    pdf.set_author("Orrix")
    pdf.set_creator("Orrix")
    pdf.set_subject(SUBTITLE)
    pdf.set_auto_page_break(auto=False, margin=_MARGIN)
    pdf.set_margins(_MARGIN, _MARGIN, _MARGIN)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 8, TITLE, new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "", 9.5)
    pdf.cell(0, 5, SUBTITLE, new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 5, f"Dispute {pack.dispute_id}", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 5, f"Generated at {pack.generated_at}", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    def section(heading: str, rows: tuple[EvidenceRow, ...]) -> None:
        if not rows:
            return
        pdf.set_font("Helvetica", "B", 10.5)
        pdf.cell(0, 6, heading, new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("Helvetica", "B", 8)
        pdf.cell(_LABEL_WIDTH, _LINE, "Field")
        pdf.cell(_VALUE_WIDTH, _LINE, "Value")
        pdf.cell(_STATUS_WIDTH, _LINE, "Status")
        pdf.cell(0, _LINE, "Origin / recorded", new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("Helvetica", "", 8)
        for row in rows:
            pdf.cell(_LABEL_WIDTH, _LINE, row.label)
            pdf.cell(_VALUE_WIDTH, _LINE, row.value)
            pdf.cell(_STATUS_WIDTH, _LINE, row.status)
            pdf.cell(
                0, _LINE, f"{row.origin} / {row.recorded_at}", new_x="LMARGIN", new_y="NEXT"
            )
        pdf.ln(2)

    section("Dispute", pack.dispute_rows)
    section("Tracking", pack.tracking_rows)
    section("Carrier report", pack.carrier_rows)

    pdf.ln(1)
    pdf.set_font("Helvetica", "B", 8)
    pdf.cell(0, _LINE, "Content hash (SHA-256)", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Courier", "", 7.5)
    pdf.cell(0, _LINE, content_hash, new_x="LMARGIN", new_y="NEXT")

    pdf.ln(3)
    pdf.set_font("Helvetica", "I", 7.5)
    pdf.multi_cell(0, 4, FOOTER_TEXT)

    output = pdf.output()
    return bytes(output), content_hash
