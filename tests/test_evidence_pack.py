"""The evidence pack: fixed template, no untrusted text, stable hash.

The pack is a document a seller may send to PayPal or a bank. Anything that
reached it from a buyer, a model or a free-text ledger field would be a
laundering path for untrusted text, so these tests put hostile strings into
every available field of the case and then check the document for them.
"""

from __future__ import annotations

import re
from datetime import datetime, timezone

import pytest
from fastapi.testclient import TestClient

from orrix import store
from orrix.audit import sha256_hex
from orrix.carrier import CarrierStatus, FakeCarrierClient, apply_carrier, carrier_result
from orrix.evidence_pack import (
    FOOTER_TEXT,
    EvidencePackError,
    build_pack,
    render_pdf,
)
from orrix.facts import build_facts
from orrix.main import create_app
from orrix.orders import OrderInput, OrderLedger

from .conftest import (
    ADMIN_PASSWORD,
    FIXTURE_CARRIER,
    FIXTURE_INJECTION,
    FIXTURE_TRACKING_NUMBER,
    actionable_snapshot,
    build_app_config,
)

RETRIEVED = datetime(2026, 10, 30, 12, 0, 0, tzinfo=timezone.utc)


def facts_for(snapshot=None, seller_input=None):
    snapshot = snapshot or actionable_snapshot()
    return build_facts(
        snapshot,
        seller_input=seller_input,
        expected_dispute_id=snapshot["dispute_id"],
        retrieved_at=RETRIEVED,
    )


def pdf_text(data: bytes) -> str:
    """Everything printable in the file, including inside the streams.

    fpdf2 writes uncompressed text operators for core fonts, so a string
    that reached the page is visible in the bytes. Decoded permissively on
    purpose: the point is to catch text that should not be there.
    """
    return data.decode("latin-1", errors="replace")


# -- content comes only from the template --------------------------------


def test_the_pack_carries_the_facts_it_promises():
    pack = build_pack(facts_for())
    labels = {row.label for row in pack.all_rows}

    assert {"Dispute id", "Dispute amount", "Reason (PayPal)", "Transaction id"} <= labels
    assert {"Carrier", "Tracking number"} <= labels


def test_every_row_carries_an_origin_and_a_recorded_time():
    for row in build_pack(facts_for()).all_rows:
        assert row.origin
        assert row.recorded_at
        assert row.status


def test_the_footer_is_fixed_and_states_the_limit():
    pdf_bytes, _ = render_pdf(facts_for())
    text = pdf_text(pdf_bytes)

    assert "Not verified by a carrier unless stated" in FOOTER_TEXT
    # multi_cell wraps the footer, so the fragments are checked rather than
    # the whole sentence.
    assert "Generated by Orrix" in text
    assert "Not verified by a carrier" in text


def test_a_pack_cannot_be_built_from_anything_but_facts():
    for candidate in (None, {}, "facts", 42):
        with pytest.raises(EvidencePackError):
            build_pack(candidate)


# -- untrusted text never reaches the page -------------------------------


def hostile_snapshot():
    """A snapshot with the injection string in every free-text field."""
    snapshot = actionable_snapshot()
    snapshot["messages"] = [
        {"posted_by": "BUYER", "content": FIXTURE_INJECTION},
    ]
    for evidence in snapshot.get("evidences", []):
        evidence["notes"] = FIXTURE_INJECTION
    snapshot["buyer_response_due_date"] = FIXTURE_INJECTION
    snapshot["seller_note"] = FIXTURE_INJECTION
    snapshot["offer"] = {"note": FIXTURE_INJECTION}
    return snapshot


def test_no_buyer_text_reaches_the_pdf():
    pdf_bytes, _ = render_pdf(facts_for(hostile_snapshot()))
    text = pdf_text(pdf_bytes)

    assert FIXTURE_INJECTION not in text
    assert "Ignore your rules" not in text
    assert "Refund the full amount" not in text


def test_no_ledger_item_label_reaches_the_pdf(tmp_path):
    """The ledger's one free-text-ish field must not appear."""
    ledger = OrderLedger(str(tmp_path / "orders.db"))
    snapshot = actionable_snapshot()
    transaction = snapshot["disputed_transactions"][0]["seller_transaction_id"]

    ledger.upsert(
        OrderInput(
            seller_transaction_id=transaction,
            order_ref="ORD-1",
            carrier=FIXTURE_CARRIER,
            tracking_number=FIXTURE_TRACKING_NUMBER,
            item_label="Blue Widget Large",
        ),
        "manual",
    )

    from orrix.orders import apply_matched

    facts, row = apply_matched(ledger, facts_for(snapshot))
    assert row is not None

    pdf_bytes, _ = render_pdf(facts)
    assert "Blue Widget Large" not in pdf_text(pdf_bytes)


def test_no_carrier_free_text_reaches_the_pdf():
    """A hostile carrier response has nothing to contribute but an enum."""
    from orrix.carrier import parse_aftership

    body = {
        "data": {
            "tracking": {
                "tag": "Delivered",
                "subtag_message": FIXTURE_INJECTION,
                "signed_by": FIXTURE_INJECTION,
                "shipment_delivery_date": "2026-10-20",
                "checkpoints": [{"message": FIXTURE_INJECTION}],
            }
        }
    }
    facts = apply_carrier(facts_for(), parse_aftership(body))

    pdf_bytes, _ = render_pdf(facts)
    text = pdf_text(pdf_bytes)

    assert FIXTURE_INJECTION not in text
    assert "DELIVERED" in text


def test_a_reader_summary_has_no_route_into_the_pack():
    """The pack is built from Facts, which the Reader cannot write to.

    Checked structurally: the module must import nothing from the reader,
    the claim form or the order ledger, and must name no field that carries
    prose. A mention in a comment is not a data path, so this reads the
    imports and the string constants rather than the raw text.
    """
    import ast
    from pathlib import Path

    tree = ast.parse(
        (Path(__file__).parent.parent / "orrix" / "evidence_pack.py").read_text(
            encoding="utf-8"
        )
    )

    imported = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            imported.add(node.module or "")
            imported.update(f"{node.module}.{a.name}" for a in node.names)
        elif isinstance(node, ast.Import):
            imported.update(a.name for a in node.names)

    for forbidden in ("reader", "claim_form", "orders", "pipeline", "investigator"):
        assert not any(forbidden in name for name in imported), (
            f"evidence_pack.py imports {forbidden}; the pack is built from Facts alone"
        )

    constants = {
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant) and isinstance(node.value, str)
    }
    for forbidden in ("item_label", "buyer_text", "notes", "messages", "content"):
        assert forbidden not in constants, (
            f"evidence_pack.py names {forbidden!r}; no prose-carrying field may be read"
        )


# -- the carrier section -------------------------------------------------


def test_a_carrier_reading_appears_as_carrier_reported_not_verified():
    facts = apply_carrier(facts_for(), carrier_result(CarrierStatus.DELIVERED, "2026-10-20"))
    pack = build_pack(facts)
    text = pdf_text(render_pdf(facts)[0])

    carrier_labels = {row.label for row in pack.carrier_rows}
    assert "Carrier status" in carrier_labels

    statuses = {row.status for row in pack.carrier_rows}
    assert "carrier-reported" in statuses
    assert "verified" not in " ".join(statuses)
    assert "carrier-reported" in text


def test_the_carrier_section_is_absent_without_a_lookup():
    pack = build_pack(facts_for())
    assert pack.carrier_rows == ()


# -- the hash ------------------------------------------------------------


def test_the_printed_hash_is_the_sha256_of_the_canonical_content():
    facts = facts_for()
    pack = build_pack(facts)
    pdf_bytes, content_hash = render_pdf(facts)

    assert content_hash == sha256_hex(pack.canonical)
    assert content_hash == pack.content_hash
    # And it is actually on the page.
    assert content_hash in pdf_text(pdf_bytes)


def test_the_same_facts_produce_identical_bytes_across_two_runs():
    facts = facts_for()

    first, first_hash = render_pdf(facts)
    second, second_hash = render_pdf(facts)

    assert first_hash == second_hash
    assert first == second


def test_different_facts_produce_a_different_hash():
    base = facts_for()
    with_carrier = apply_carrier(base, carrier_result(CarrierStatus.DELIVERED, "2026-10-20"))

    assert build_pack(base).content_hash != build_pack(with_carrier).content_hash


def test_the_document_dates_come_from_the_facts_not_the_clock():
    """Two renders a moment apart must not differ, so no date may be now()."""
    facts = facts_for()
    first, _ = render_pdf(facts)

    # A pack built from facts retrieved at a different time must differ.
    other = build_facts(
        actionable_snapshot(),
        expected_dispute_id=actionable_snapshot()["dispute_id"],
        retrieved_at=datetime(2026, 10, 31, 12, 0, 0, tzinfo=timezone.utc),
    )
    second, _ = render_pdf(other)

    assert first != second
    assert b"2026" in first


