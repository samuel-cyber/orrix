@pytest.fixture
def pdf_client(tmp_path, monkeypatch):
    monkeypatch.setenv("ORRIX_DB_PATH", str(tmp_path / "test.db"))
    monkeypatch.setenv("POLLER_ENABLED", "false")
    store.init_db()

    snapshot = actionable_snapshot()
    store.save_case_snapshot(snapshot["dispute_id"], snapshot)

    config = build_app_config(tmp_path)
    with TestClient(create_app(config=config)) as client:
        yield client, snapshot["dispute_id"]


def test_the_pdf_route_requires_a_session(pdf_client):
    client, dispute_id = pdf_client

    response = client.get(f"/cases/{dispute_id}/evidence.pdf", follow_redirects=False)

    assert response.status_code in (302, 303, 307, 401, 403)
    assert b"%PDF" not in response.content


def test_the_pdf_route_serves_a_pdf_with_the_right_headers(pdf_client):
    client, dispute_id = pdf_client
    client.post("/login", data={"password": ADMIN_PASSWORD}, follow_redirects=False)

    response = client.get(f"/cases/{dispute_id}/evidence.pdf")

    assert response.status_code == 200
    assert response.headers["content-type"] == "application/pdf"
    assert "attachment" in response.headers["content-disposition"]
    assert dispute_id in response.headers["content-disposition"]
    assert response.headers["x-content-type-options"] == "nosniff"
    assert "no-store" in response.headers["cache-control"]
    assert response.content.startswith(b"%PDF")


def test_the_page_shows_the_same_hash_the_file_carries(pdf_client):
    client, dispute_id = pdf_client
    client.post("/login", data={"password": ADMIN_PASSWORD}, follow_redirects=False)

    page = client.get(f"/cases/{dispute_id}")
    download = client.get(f"/cases/{dispute_id}/evidence.pdf")

    shown = re.search(r"sha256 ([0-9a-f]{16})", page.text)
    assert shown is not None

    full = download.headers["x-orrix-content-hash"]
    assert full.startswith(shown.group(1))
    assert full in pdf_text(download.content)


def test_the_download_is_byte_identical_on_a_second_request(pdf_client):
    client, dispute_id = pdf_client
    client.post("/login", data={"password": ADMIN_PASSWORD}, follow_redirects=False)

    first = client.get(f"/cases/{dispute_id}/evidence.pdf").content
    second = client.get(f"/cases/{dispute_id}/evidence.pdf").content

    assert first == second


def test_an_unknown_case_has_no_pack(pdf_client):
    client, _ = pdf_client
    client.post("/login", data={"password": ADMIN_PASSWORD}, follow_redirects=False)

    response = client.get("/cases/PP-D-NO-SUCH-CASE/evidence.pdf")

    assert response.status_code == 404
    assert not response.content.startswith(b"%PDF")


def test_the_pdf_route_makes_no_carrier_lookup(tmp_path, monkeypatch):
    """A download must not be a way to spend the carrier budget."""
    monkeypatch.setenv("ORRIX_DB_PATH", str(tmp_path / "test.db"))
    monkeypatch.setenv("POLLER_ENABLED", "false")
    store.init_db()

    snapshot = actionable_snapshot()
    store.save_case_snapshot(snapshot["dispute_id"], snapshot)

    spy = FakeCarrierClient({"tag": "Delivered"})
    config = build_app_config(
        tmp_path, carrier_enabled=True, carrier_api_provider="aftership", carrier_api_key="k"
    )

    with TestClient(create_app(config=config, carrier_client=spy)) as client:
        client.post("/login", data={"password": ADMIN_PASSWORD}, follow_redirects=False)
        before = spy.call_count
        client.get(f"/cases/{snapshot['dispute_id']}/evidence.pdf")

    assert spy.call_count == before
